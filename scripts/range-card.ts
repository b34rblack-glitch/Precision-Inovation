// Reference range cards for the two Phoenix rifles, run through the app's own
// solver so docs/range-cards/ carries the same numbers the app shows.
//
//   npx vite-node --config vitest.config.ts scripts/range-card.ts cross|mpr [text|json|md]
//
// Rifle, load and zero-session data come from scripts/workspace-phoenix.ts so
// the printed cards and the importable workspace cannot drift apart.
import { solveTrajectory } from '@/lib/ballistics/solver';
import { BallisticInput } from '@/lib/ballistics/types';
import { icaoPressureAtAltitude } from '@/lib/ballistics/atmosphere';
import { formatHold, paToInHg, parseTwistRate, roundHold } from '@/lib/units';
import { CROSS, MPR, ZERO_RANGE } from './workspace-phoenix';

export type Conditions = {
  key: string;
  label: string;
  tempF: number;
  altitudeFt: number;
  humidityPct: number;
};

/** Station pressure from ICAO altitude, so the condition sets stay comparable. */
export const stationPressureInHg = (altitudeFt: number) =>
  paToInHg(icaoPressureAtAltitude(altitudeFt));

export const CONDITIONS: Conditions[] = [
  { key: 'zero', label: 'Zero day, Phoenix Rod and Gun Club, 4 Oct 2026 10:00', tempF: ZERO_RANGE.tempF, altitudeFt: ZERO_RANGE.altitudeFt, humidityPct: ZERO_RANGE.humidityPct },
  { key: 'phx-hot', label: 'Phoenix, summer afternoon', tempF: 105, altitudeFt: 1100, humidityPct: 10 },
  { key: 'winter', label: 'Phoenix, winter dawn', tempF: 40, altitudeFt: 1100, humidityPct: 40 },
  { key: 'rim', label: 'Mogollon Rim hunt', tempF: 45, altitudeFt: 6500, humidityPct: 30 },
];

const RIFLES = { cross: CROSS, mpr: MPR } as const;
type RifleKey = keyof typeof RIFLES;

const FILE_SLUG: Record<RifleKey, string> = {
  cross: 'sig-cross-magnum-300wm-terminal-ascent-175',
  mpr: 'christensen-mpr-300prc-eld-x-212',
};

export function inputFor(key: RifleKey, c: Conditions, maxDistanceYd = 1000, stepYd = 25): BallisticInput {
  const spec = RIFLES[key];
  return {
    mvFps: spec.version.muzzleVelocityFps!,
    bc: spec.version.bcValue!,
    bcModel: spec.version.bcModel!,
    zeroDistanceYd: spec.rifle.zeroDistance,
    sightHeightIn: spec.rifle.sightHeightIn,
    atmo: { tempF: c.tempF, pressureInHg: stationPressureInHg(c.altitudeFt), humidityPct: c.humidityPct },
    windMph: 10,
    maxDistanceYd,
    stepYd,
    bulletWeightGr: spec.version.bulletWeightGr,
    spin: {
      twistInPerTurn: parseTwistRate(spec.rifle.twistRate!)!,
      twistRight: spec.rifle.twistRight,
      bulletLengthIn: spec.version.bulletLengthIn!,
      bulletDiameterIn: spec.version.bulletDiameterIn!,
    },
  };
}

const key = (process.argv[2] ?? 'cross') as RifleKey;
if (!(key in RIFLES)) throw new Error(`unknown rifle "${key}"; use cross or mpr`);
const mode = process.argv[3] ?? 'text';
const spec = RIFLES[key];
const unit = spec.rifle.turretUnit;
const hold = (v: number) => formatHold(roundHold(v, unit), unit);
const condLine = (c: Conditions) =>
  `${c.tempF} °F · ${c.altitudeFt.toLocaleString('en-US')} ft · ${stationPressureInHg(c.altitudeFt).toFixed(2)} inHg station · ${c.humidityPct}% RH`;

if (mode === 'md') {
  const v = spec.version;
  const lines: string[] = [];
  lines.push(`# ${spec.rifle.name} · ${spec.loadName.replace(' (factory)', '')}`);
  lines.push('');
  lines.push(`Range card, ${spec.rifle.zeroDistance} yd zero, generated by \`scripts/range-card.ts ${key} md\` with the app's solver.`);
  lines.push(`Interactive version with live conditions: \`phoenix-rifle-dope.html\` in this folder. Import the rifle and load into the app with \`phoenix-workspace.json\`.`);
  lines.push('');
  lines.push('| Rifle system | |');
  lines.push('|---|---|');
  lines.push(`| Rifle | ${spec.rifle.make} ${spec.rifle.model}, ${spec.rifle.cartridge}, ${spec.rifle.barrelLengthIn}" barrel, ${spec.rifle.twistRate} RH twist |`);
  lines.push(`| Ammunition | ${spec.loadName.replace(' (factory)', '')} · ${v.muzzleVelocityFps} fps published (24" test barrel) · ${v.bcModel} ${v.bcValue} · ${v.bulletWeightGr} gr, ${v.bulletLengthIn}" long |`);
  lines.push(`| Optic | ${spec.rifle.scopeMake} ${spec.rifle.scopeModel} |`);
  lines.push(`| Sight height | ${spec.rifle.sightHeightIn}" over bore (estimate, measure it) |`);
  lines.push(`| Zero | ${spec.rifle.zeroDistance} yd, ${ZERO_RANGE.location}, 4 Oct 2026 |`);
  lines.push('');
  lines.push(`Elev is the dial-up or holdover in ${unit}, rounded to the turret click (${unit === 'MIL' ? '0.1 MIL' : '1/4 MOA'}). Wind is the full-value hold for a 10 mph crosswind; halve it for 45°. Drift is spin drift (${spec.rifle.twistRate} RH twist), hold left. Path is inches relative to the line of sight, negative = low.`);
  lines.push('');
  for (const c of CONDITIONS) {
    const rows = solveTrajectory(inputFor(key, c, 1000, 50));
    lines.push(`## ${c.label}`);
    lines.push('');
    lines.push(condLine(c));
    lines.push('');
    lines.push(`| Yards | Path in | Elev ${unit} | Elev ${unit === 'MIL' ? 'MOA' : 'MIL'} | Wind 10 ${unit} | Drift ${unit} | fps | ft·lb | TOF s |`);
    lines.push('|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
    for (const r of rows) {
      const primary = unit === 'MIL' ? r.dropMil : r.dropMoa;
      const secondary = unit === 'MIL' ? r.dropMoa.toFixed(2) : r.dropMil.toFixed(1);
      const wind = unit === 'MIL' ? r.windMil : r.windMoa;
      const drift = unit === 'MIL' ? r.driftMil : r.driftMoa;
      const driftText = drift < (unit === 'MIL' ? 0.05 : 0.125) ? '—' : `${hold(drift)} L`;
      lines.push(
        `| ${r.distanceYd} | ${r.dropIn.toFixed(1)} | **${hold(primary)}** | ${secondary} | ${hold(wind)} | ${driftText} | ${Math.round(r.velocityFps).toLocaleString('en-US')} | ${Math.round(r.energyFtLb ?? 0).toLocaleString('en-US')} | ${r.tofS.toFixed(3)} |`,
      );
    }
    lines.push('');
  }
  lines.push('## Before trusting it');
  lines.push('');
  lines.push(`- Chronograph the load and replace the published ${v.muzzleVelocityFps} fps; rifles commonly run 20 to 60 fps off the test barrel${spec.rifle.barrelLengthIn! > 24 ? ', and this barrel is longer than the test barrel' : ''}.`);
  lines.push(`- Measure sight height (bore center to scope-tube center). ${spec.rifle.sightHeightIn}" is an estimate built from the published ring height plus about 0.85" from bore to rail top.`);
  lines.push('- Confirm the 100 yd zero, then true muzzle velocity against impacts at 500 to 600 yd before relying on holds past that.');
  lines.push("- Condition sets change air density only; the load's powder temperature sensitivity is not published and is not modeled.");
  lines.push('');
  console.log(lines.join('\n'));
} else {
  const out: Record<string, unknown> = { rifle: key, spec, conditions: {} };
  for (const c of CONDITIONS) {
    const rows = solveTrajectory(inputFor(key, c));
    (out.conditions as Record<string, unknown>)[c.key] = { ...c, pressureInHg: stationPressureInHg(c.altitudeFt), rows };
    if (mode !== 'json') {
      console.log(`\n== ${spec.rifle.name} · ${c.label}: ${condLine(c)} ==`);
      console.log(`yd    drop in   MIL    MOA   W10 ${unit.padEnd(3)}  drift ${unit}   fps   ft·lb   tof`);
      for (const r of rows) {
        if (r.distanceYd % 50 !== 0) continue;
        console.log(
          [
            String(r.distanceYd).padStart(4),
            r.dropIn.toFixed(1).padStart(8),
            r.dropMil.toFixed(1).padStart(6),
            r.dropMoa.toFixed(2).padStart(7),
            hold(unit === 'MIL' ? r.windMil : r.windMoa).padStart(8),
            hold(unit === 'MIL' ? r.driftMil : r.driftMoa).padStart(9),
            Math.round(r.velocityFps).toString().padStart(7),
            Math.round(r.energyFtLb ?? 0).toString().padStart(7),
            r.tofS.toFixed(3).padStart(6),
          ].join(' '),
        );
      }
    }
  }
  if (mode === 'json') console.log(JSON.stringify(out));
}
export const FILE_SLUGS = FILE_SLUG;
