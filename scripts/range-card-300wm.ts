// Reference range card: SIG CROSS Magnum (.300 Win Mag, 24" 1:9 RH) shooting
// Federal Premium Terminal Ascent 175 gr (P300WTA2), 100 yd zero, Phoenix AZ.
//
// Runs the app's own solver so the numbers in docs/range-cards/ come from the
// same engine the app uses. Usage:
//   npx vite-node --config vitest.config.ts scripts/range-card-300wm.ts [json]
import { solveTrajectory } from '@/lib/ballistics/solver';
import { BallisticInput } from '@/lib/ballistics/types';
import { icaoPressureAtAltitude } from '@/lib/ballistics/atmosphere';
import { paToInHg } from '@/lib/units';

export const LOAD = {
  rifle: 'SIG CROSS Magnum .300 Win Mag, 24" 5R, 1:9 RH',
  ammo: 'Federal Premium Terminal Ascent 175 gr (P300WTA2)',
  mvFps: 3030, // Federal published, 24" test barrel
  bcG7: 0.258, // Federal published
  bcG1: 0.52,
  bulletWeightGr: 175,
  bulletLengthIn: 1.466,
  bulletDiameterIn: 0.308,
  twistInPerTurn: 9,
  zeroDistanceYd: 100,
  // ALPHA6 34 mm extra-high rings: 1.25" rail top → optic centerline (SIG)
  // + ≈0.85" bore centerline → top of the CROSS's integral rail (estimate).
  sightHeightIn: 2.1,
};

export type Conditions = {
  key: string;
  label: string;
  tempF: number;
  altitudeFt: number;
  humidityPct: number;
};

/** Station pressure from ICAO altitude, so the three sets stay comparable. */
export const stationPressureInHg = (altitudeFt: number) =>
  paToInHg(icaoPressureAtAltitude(altitudeFt));

export const CONDITIONS: Conditions[] = [
  { key: 'phx', label: 'Phoenix, mild day (zero conditions)', tempF: 75, altitudeFt: 1100, humidityPct: 20 },
  { key: 'phx-hot', label: 'Phoenix, summer afternoon', tempF: 105, altitudeFt: 1100, humidityPct: 10 },
  { key: 'rim', label: 'Mogollon Rim hunt', tempF: 45, altitudeFt: 6500, humidityPct: 30 },
];

export function inputFor(c: Conditions, maxDistanceYd = 1000, stepYd = 25): BallisticInput {
  return {
    mvFps: LOAD.mvFps,
    bc: LOAD.bcG7,
    bcModel: 'G7',
    zeroDistanceYd: LOAD.zeroDistanceYd,
    sightHeightIn: LOAD.sightHeightIn,
    atmo: {
      tempF: c.tempF,
      pressureInHg: stationPressureInHg(c.altitudeFt),
      humidityPct: c.humidityPct,
    },
    windMph: 10,
    maxDistanceYd,
    stepYd,
    bulletWeightGr: LOAD.bulletWeightGr,
    spin: {
      twistInPerTurn: LOAD.twistInPerTurn,
      twistRight: true,
      bulletLengthIn: LOAD.bulletLengthIn,
      bulletDiameterIn: LOAD.bulletDiameterIn,
    },
  };
}

const mode = process.argv.includes('json') ? 'json' : process.argv.includes('md') ? 'md' : 'text';
if (mode === 'md') {
  // Printable card: docs/range-cards/*.md. 50 yd rows to 1000 yd, one table per condition set.
  const lines: string[] = [];
  lines.push('# SIG CROSS Magnum .300 Win Mag · Federal Terminal Ascent 175 gr');
  lines.push('');
  lines.push('Range card, 100 yd zero, generated by `scripts/range-card-300wm.ts` with the app\'s solver.');
  lines.push('Interactive version with live conditions: `sig-cross-magnum-300wm-terminal-ascent-175.html` in this folder.');
  lines.push('');
  lines.push('| Rifle system | |');
  lines.push('|---|---|');
  lines.push(`| Rifle | ${LOAD.rifle} |`);
  lines.push(`| Ammunition | ${LOAD.ammo} · ${LOAD.mvFps} fps published (24" test barrel) · G7 ${LOAD.bcG7} / G1 ${LOAD.bcG1} · ${LOAD.bulletWeightGr} gr, ${LOAD.bulletLengthIn}" long |`);
  lines.push('| Optic | Leupold Mark 4HD 4.5-18×52, 34 mm, FFP illuminated PR1-MIL, 0.1 MIL clicks |');
  lines.push(`| Mount | SIG ALPHA6 34 mm extra-high rings (1.25" rail to centerline) · sight height ${LOAD.sightHeightIn}" over bore (estimate, measure it) |`);
  lines.push(`| Zero | ${LOAD.zeroDistanceYd} yd, Phoenix AZ |`);
  lines.push('');
  lines.push('Elev is the dial-up or holdover, rounded to the 0.1 MIL click. Wind is the full-value hold for a 10 mph crosswind; halve it for 45°. Drift is spin drift (1:9 RH twist), hold left. Path is inches relative to the line of sight, negative = low.');
  lines.push('');
  for (const c of CONDITIONS) {
    const rows = solveTrajectory(inputFor(c, 1000, 50));
    lines.push(`## ${c.label}`);
    lines.push('');
    lines.push(`${c.tempF} °F · ${c.altitudeFt.toLocaleString('en-US')} ft · ${stationPressureInHg(c.altitudeFt).toFixed(2)} inHg station · ${c.humidityPct}% RH`);
    lines.push('');
    lines.push('| Yards | Path in | Elev MIL | Elev MOA | Wind 10 MIL | Drift MIL | fps | ft·lb | TOF s |');
    lines.push('|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
    for (const r of rows) {
      const drift = r.driftMil < 0.05 ? '—' : `${r.driftMil.toFixed(1)} L`;
      lines.push(
        `| ${r.distanceYd} | ${r.dropIn.toFixed(1)} | **${r.dropMil.toFixed(1)}** | ${r.dropMoa.toFixed(2)} | ${r.windMil.toFixed(1)} | ${drift} | ${Math.round(r.velocityFps).toLocaleString('en-US')} | ${Math.round(r.energyFtLb ?? 0).toLocaleString('en-US')} | ${r.tofS.toFixed(3)} |`,
      );
    }
    lines.push('');
  }
  lines.push('## Before trusting it');
  lines.push('');
  lines.push('- Chronograph the load and replace the published 3,030 fps; rifles commonly run 20 to 60 fps off the test barrel.');
  lines.push('- Measure sight height (bore center to scope-tube center). 2.1" is 1.25" of ring plus an estimated 0.85" from bore to the top of the CROSS rail.');
  lines.push('- Confirm the 100 yd zero, then true muzzle velocity against impacts at 500 to 600 yd before relying on holds past that.');
  lines.push('- Condition sets change air density only; the load\'s powder temperature sensitivity is not published and is not modeled.');
  lines.push('');
  lines.push('Sources: Federal P300WTA2 product listing (3,030 fps, G7 .258, G1 .520, 1.466" bullet); SIG SAUER CROSS Magnum specs (24" 1:9 barrel); SIG ALPHA6 34 mm rings (extra high 1.25").');
  console.log(lines.join('\n'));
}
if (mode !== 'md') {
  const asJson = mode === 'json';
  const out: Record<string, unknown> = { load: LOAD, conditions: {} };
  for (const c of CONDITIONS) {
    const rows = solveTrajectory(inputFor(c));
    (out.conditions as Record<string, unknown>)[c.key] = {
      ...c,
      pressureInHg: stationPressureInHg(c.altitudeFt),
      rows,
    };
    if (!asJson) {
      console.log(`\n== ${c.label}: ${c.tempF}°F, ${c.altitudeFt} ft, ${stationPressureInHg(c.altitudeFt).toFixed(2)} inHg, ${c.humidityPct}% RH ==`);
      console.log('yd    drop in   MIL    MOA   W10 MIL  drift MIL   fps   ft·lb   tof');
      for (const r of rows) {
        if (r.distanceYd % 50 !== 0) continue;
        console.log(
          [
            String(r.distanceYd).padStart(4),
            r.dropIn.toFixed(1).padStart(8),
            r.dropMil.toFixed(1).padStart(6),
            r.dropMoa.toFixed(2).padStart(7),
            r.windMil.toFixed(1).padStart(8),
            r.driftMil.toFixed(2).padStart(9),
            Math.round(r.velocityFps).toString().padStart(7),
            Math.round(r.energyFtLb ?? 0).toString().padStart(7),
            r.tofS.toFixed(3).padStart(6),
          ].join(' '),
        );
      }
    }
  }
  if (asJson) console.log(JSON.stringify(out));
}
